#!/usr/bin/env bash
# Regenerates setup_all.sql (migrations + seed in order) for one-paste setup
# in the Supabase SQL Editor. Run after changing a migration or seed.sql.
set -euo pipefail
cd "$(dirname "$0")"
{
  printf -- "-- DriveSync database setup: everything in one file.\n--\n"
  printf -- "-- Paste this whole file into Supabase → SQL Editor → New query → Run, ONCE.\n"
  printf -- "-- It is the migrations plus the seed, in order (generated by\n"
  printf -- "-- build_setup_all.sh from supabase/migrations/*.sql and supabase/seed.sql).\n\n"
  for f in migrations/*.sql seed.sql; do
    printf -- "-- ═════════ %s ═════════\n\n" "$f"
    cat "$f"
    printf "\n\n"
  done
} > "${1:-setup_all.sql}"
